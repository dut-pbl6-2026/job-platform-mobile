import 'dart:typed_data';

final class AiChatReply {
  const AiChatReply({required this.response, required this.sessionId});
  final String response;
  final String sessionId;

  AiChatReply copyWith({String? response, String? sessionId}) => AiChatReply(
    response: response ?? this.response,
    sessionId: sessionId ?? this.sessionId,
  );
}

final class ResumeFeedback {
  const ResumeFeedback({
    required this.score,
    this.matchingSkills = const [],
    this.missingSkills = const [],
    this.extraSkills = const [],
    this.skillsScore,
    this.experienceScore,
    this.experienceYears,
    this.requiredExperienceYears,
    this.experienceRelevance,
    this.educationScore,
    this.educationDegree,
    this.requiredEducationDegree,
    this.educationRelevance,
    this.suggestions = const [],
  });

  /// Overall match score (0 - 100) per SRS 5.3.2 & 5.3.4
  final double score;

  /// Matching skills extracted from CV and Job Requirements (SCORE-01-03)
  final List<String> matchingSkills;

  /// Missing skills required by Job Description but missing from CV
  final List<String> missingSkills;

  /// Extra relevant skills found in CV beyond job requirements
  final List<String> extraSkills;

  /// Sub-score for skills match (0 - 100)
  final double? skillsScore;

  /// Sub-score for experience match (0 - 100)
  final double? experienceScore;

  /// Candidate years of experience extracted from CV
  final num? experienceYears;

  /// Required years of experience per job description
  final num? requiredExperienceYears;

  /// Experience relevance level (e.g. 'High', 'Medium', 'Match')
  final String? experienceRelevance;

  /// Sub-score for education match (0 - 100)
  final double? educationScore;

  /// Candidate degree extracted from CV
  final String? educationDegree;

  /// Required degree per job description
  final String? requiredEducationDegree;

  /// Education relevance / match status (e.g. 'Match', 'Related')
  final String? educationRelevance;

  /// Actionable suggestions generated by AI to improve CV (SCORE-01-04)
  final List<String> suggestions;

  ResumeFeedback copyWith({
    double? score,
    List<String>? matchingSkills,
    List<String>? missingSkills,
    List<String>? extraSkills,
    double? skillsScore,
    double? experienceScore,
    num? experienceYears,
    num? requiredExperienceYears,
    String? experienceRelevance,
    double? educationScore,
    String? educationDegree,
    String? requiredEducationDegree,
    String? educationRelevance,
    List<String>? suggestions,
  }) => ResumeFeedback(
    score: score ?? this.score,
    matchingSkills: List.unmodifiable(matchingSkills ?? this.matchingSkills),
    missingSkills: List.unmodifiable(missingSkills ?? this.missingSkills),
    extraSkills: List.unmodifiable(extraSkills ?? this.extraSkills),
    skillsScore: skillsScore ?? this.skillsScore,
    experienceScore: experienceScore ?? this.experienceScore,
    experienceYears: experienceYears ?? this.experienceYears,
    requiredExperienceYears:
        requiredExperienceYears ?? this.requiredExperienceYears,
    experienceRelevance: experienceRelevance ?? this.experienceRelevance,
    educationScore: educationScore ?? this.educationScore,
    educationDegree: educationDegree ?? this.educationDegree,
    requiredEducationDegree:
        requiredEducationDegree ?? this.requiredEducationDegree,
    educationRelevance: educationRelevance ?? this.educationRelevance,
    suggestions: List.unmodifiable(suggestions ?? this.suggestions),
  );
}

final class AiCvInput {
  const AiCvInput({
    required this.name,
    required this.size,
    this.bytes,
    this.path,
  });
  final String name;
  final int size;
  final Uint8List? bytes;
  final String? path;
}

final class AiFailure implements Exception {
  const AiFailure(this.message, {this.cancelled = false});
  final String message;
  final bool cancelled;
  @override
  String toString() => message;
}

/// Gateway contracts from SRS 5.2.3 and 5.3.3 (AI-01, SCORE-01).
abstract interface class IAiRepository {
  Future<AiChatReply> sendMessage(String message, {String? sessionId});
  Future<ResumeFeedback> scoreResume(AiCvInput cv, {required String jobId});
  void cancelCurrentRequest();
}
